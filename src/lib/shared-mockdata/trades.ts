export const tradesToCsv = (trades: TradeRecord[]): string => {
	const header =
		'Trade ID,Symbol,Long/Short,Entry Date,Entry Price,Exit Date,Exit Price,Quantity,Commission,Slippage,Net PnL,Return %,Holding Days,Exit Reason';
	const rows = trades.map((t) =>
		[
			t.tradeId,
			t.symbol,
			t.direction,
			t.entryDate,
			t.entryPrice,
			t.exitDate,
			t.exitPrice,
			t.quantity,
			t.commission,
			t.slippage,
			t.netPnl,
			t.returnPct,
			t.holdingDays,
			t.exitReason
		].join(',')
	);
	return [header, ...rows].join('\n');
};
